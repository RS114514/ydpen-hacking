CLUE_FIX = {
    'C_SQ1_09': '擦亮民国老闸刀留下的紫铜碎末；顺纹擦，不留沟，合闸不打火。',
}

FILES = ['script_vol1_autumn.json', 'script_vol4_summer.json']


def main():
    bad = []
    for qid, lines in LINES.items():
        for sp, tx in lines:
            if len(tx) > MAX:
                bad.append((qid, len(tx), tx))
        if not 4 <= len(lines) <= 6:
            bad.append((qid, len(lines), '句数越界'))
        if sum(1 for s, _ in lines if s == '池雨曦') < 1:
            bad.append((qid, 0, '缺池雨曦点评'))
    if bad:
        for b in bad:
            print('! 违规', b)
        raise SystemExit(1)

    touched = 0
    for fn in FILES:
        path = os.path.join(HERE, fn)
        data = json.load(open(path, encoding='utf-8'))
        for ch in data['chapters']:
            for inv in ch.get('investigations', []):
                qid = inv.get('id')
                if qid in LINES:
                    inv['lines'] = [{'speaker': s, 'text': t} for s, t in LINES[qid]]
                    touched += 1
                cid = (inv.get('clue') or {}).get('id')
                if cid in CLUE_FIX:
                    inv['clue']['desc'] = CLUE_FIX[cid]
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write('\n')
    print('扩写条目 %d / 目标 %d' % (touched, len(LINES)))


if __name__ == '__main__':
    main()
